    public int numTriplets(int[] nums1, int[] nums2) {
        Arrays.sort(nums1);
        Arrays.sort(nums2);
        return calc(nums1, nums2) + calc(nums2, nums1);
    }

    private int calc(int[] nums1, int[] nums2) {
        int res = 0;
        var count = new HashMap<Integer, Integer>();
        for (int num : nums2) {
            count.merge(num, 1, Integer::sum);
        }
        for (int num : nums1) {
            long product = (long) num * num;
            int i = 0, j = nums2.length - 1;
            while (i < j) {
                long t = (long) nums2[i] * nums2[j];
                if (product == t) {
                    res += (int) (nums2[i] == nums2[j] ?
                                                (count.get(nums2[i]) - 1) * count.get(nums2[i]) / 2 :
                                                count.get(nums2[i]) * count.get(nums2[j]));
                    for (i++; i < j && nums2[i] == nums2[i - 1]; i++);
                    for (j--; i < j && nums2[j] == nums2[j + 1]; j--);
                } else if (product > t) {
                    for (i++; i < j && nums2[i] == nums2[i - 1]; i++);
                } else {
                    for (j--; i < j && nums2[j] == nums2[j + 1]; j--);
                }
            }
        }
        return res;
    }

